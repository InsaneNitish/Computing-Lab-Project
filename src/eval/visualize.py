"""Visualise the model, its parameters, the LoRA adapter weights, model outputs and results.

Everything is written to results/figures/ (PNG, CSV, TXT, HTML, README.md) so it can be
committed to GitHub; GitHub renders results/figures/README.md with every figure embedded.

Run from the repo root:
  python -m src.eval.visualize results            # leak heatmaps, bar summaries, loss curves   (CPU, no model)
  python -m src.eval.visualize adapters           # per-layer/module LoRA weight-change norms    (CPU, no model)
  python -m src.eval.visualize arch               # architecture diagram + parameter tables      (config only, no weights)
  python -m src.eval.visualize outputs            # generated answers before/after unlearning    (GPU; HTML report)
  python -m src.eval.visualize all                # every step above; a failing step is skipped with a message

Useful flags: --method ga  --unlearn_langs hindi kannada  --query_langs english hindi kannada
              --n 5 (questions per language in the outputs report)  --nli (colour answers by NLI verdict)
"""
