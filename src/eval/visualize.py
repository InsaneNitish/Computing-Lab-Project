# ------------------------------------------------------------------ ADAPTERS (safetensors only)
def load_lora_tensors(adapter_dir):
    path = os.path.join(adapter_dir, "adapter_model.safetensors")
    try:  # LoRA weights are fp32 by default, which numpy can read
        from safetensors import safe_open
        out = {}
        with safe_open(path, framework="np") as f:
            for k in f.keys():
                out[k] = f.get_tensor(k).astype(np.float32)
        return out
    except Exception:  # e.g. bf16 weights: fall back to torch
        from safetensors.torch import load_file
        return {k: v.float().numpy() for k, v in load_file(path).items()}


def adapter_delta_norms(adapter_dir):
    """Frobenius norm of the weight change  scaling * B @ A  for every (layer, module)."""
    with open(os.path.join(adapter_dir, "adapter_config.json"), encoding="utf-8") as f:
        cfg = json.load(f)
    scaling = cfg["lora_alpha"] / cfg["r"]
    tensors = load_lora_tensors(adapter_dir)
    pairs, sample = {}, {"A": [], "B": []}
    for key, arr in tensors.items():
        m = LORA_RE.search(key)
        if not m:
            continue
        layer, module, ab = int(m.group(1)), m.group(2), m.group(3)
        pairs.setdefault((layer, module), {})[ab] = arr
        flat = arr.ravel()
        sample[ab].append(flat[:: max(1, len(flat) // 20000)])
    norms = {k: float(np.linalg.norm(scaling * (v["B"] @ v["A"])))
             for k, v in pairs.items() if "A" in v and "B" in v}
    return norms, {ab: (np.concatenate(v) if v else np.zeros(1)) for ab, v in sample.items()}, cfg


def cmd_adapters(args):
    dirs = args.adapters or sorted(os.path.dirname(p) for p in glob.glob("checkpoints/*/adapter_config.json"))
    if not dirs:
        print("[adapters] no adapters found under checkpoints/ (download them from Kaggle first)")
        return
    data = OrderedDict()
    for d in dirs:
        norms, sample, cfg = adapter_delta_norms(d)
        if norms:
            data[os.path.basename(os.path.normpath(d))] = (norms, sample, cfg)
    if not data:
        print("[adapters] adapter files contained no recognisable LoRA tensors")
        return

    rows = [(name, l, m, f"{v:.6f}") for name, (norms, _, _) in data.items() for (l, m), v in sorted(norms.items())]
    write_csv(args.out, "adapter_delta_norms.csv", ["adapter", "layer", "module", "delta_frobenius_norm"], rows)

    for name, (norms, _, cfg) in data.items():  # layer x module heatmap
        layers = sorted({l for l, _ in norms})
        grid = np.array([[norms.get((l, m), np.nan) for l in layers] for m in MODULES])
        fig, ax = plt.subplots(figsize=(max(7, 0.55 * len(layers) + 3), 3.8))
        im = ax.imshow(grid, aspect="auto", cmap="magma")
        ax.set_xticks(range(len(layers)))
        ax.set_xticklabels(layers)
        ax.set_yticks(range(len(MODULES)))
        ax.set_yticklabels(MODULES)
        ax.set_xlabel("transformer layer")
        ax.set_title(f"{name}: size of the weight change per module (r={cfg['r']}, alpha={cfg['lora_alpha']})")
        fig.colorbar(im, ax=ax, label="||delta W||_F")
        savefig(fig, args.out, f"adapter_heatmap_{name}.png")

    fig, axes = plt.subplots(len(data), 1, figsize=(10, 2.8 * len(data)), squeeze=False)  # per-layer stacked bars
    for ax, (name, (norms, _, _)) in zip(axes[:, 0], data.items()):
        layers = sorted({l for l, _ in norms})
        bottom = np.zeros(len(layers))
        for m, color in zip(MODULES, MODULE_COLORS):
            vals = np.array([norms.get((l, m), 0.0) for l in layers])
            ax.bar(layers, vals, bottom=bottom, color=color, label=m, width=0.8)
            bottom += vals
        ax.set_ylabel("sum ||delta W||_F")
        ax.set_title(name, fontsize=10, loc="left")
    axes[-1, 0].set_xlabel("transformer layer (low = early, high = late)")
    axes[0, 0].legend(ncol=7, fontsize=7, loc="lower center", bbox_to_anchor=(0.5, 1.25))
    fig.suptitle("Where in the network does each adapter change the model?", y=1.0)
    fig.tight_layout()
    savefig(fig, args.out, "adapter_layer_norms.png")

    fig, axes = plt.subplots(1, 2, figsize=(10, 3.6), sharey=True)  # weight distributions
    for ab, ax in zip("AB", axes):
        for name, (_, sample, _) in data.items():
            ax.hist(sample[ab], bins=80, histtype="step", label=name, log=True)
        ax.set_title(f"LoRA {ab} matrices: weight distribution")
        ax.set_xlabel("weight value")
    axes[0].set_ylabel("count (log)")
    axes[1].legend(fontsize=7)
    savefig(fig, args.out, "adapter_weight_hist.png")


# ------------------------------------------------------------------ ARCHITECTURE (config only)
def classify(name):
    n = name.lower()
    if "embed_tokens" in n or "wte" in n:
        return "token embeddings"
    if "lm_head" in n:
        return "lm_head"
    for m in MODULES:
        if m in n:
            return ("attention." if m in ATTN else "mlp.") + m
    if "norm" in n:
        return "layer norms"
    return "other"


def summarise_base(items):
    tot = {}
    for name, n in items:
        c = classify(name)
        tot[c] = tot.get(c, 0) + n
    return OrderedDict((c, tot[c]) for c in CATEGORY_ORDER if c in tot)


