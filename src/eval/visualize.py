def build_arch(base_items, lora_items, cfg, model_name, rank, arch_text, out):
    """Torch-free: turns (name, numel) and (layer, module, params) lists into tables and figures."""
    summary = summarise_base(base_items)
    base_total = sum(summary.values())
    lora_total = sum(p for _, _, p in lora_items)

    write_csv(out, "param_table.csv", ["component", "parameters", "percent_of_model"],
              [(c, n, f"{100 * n / base_total:.2f}") for c, n in summary.items()])
    write_csv(out, "lora_param_table.csv", ["layer", "module", "lora_parameters"], sorted(lora_items))

    header = [f"model: {model_name}", f"total base parameters: {base_total:,}",
              f"LoRA (r={rank}) trainable parameters: {lora_total:,} ({100 * lora_total / base_total:.3f}% of base)",
              f"weights in fp16/bf16 would take about {base_total * 2 / 1e9:.2f} GB; "
              f"LoRA adapter about {lora_total * 4 / 1e6:.0f} MB in fp32", ""]
    if cfg.get("tied"):
        header.append("note: lm_head is tied to the token embeddings, so it is not counted twice")
    header += ["", "component                      parameters   percent"]
    header += [f"{c:<28} {n:>12,} {100 * n / base_total:>8.2f}%" for c, n in summary.items()]
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, "model_architecture.txt"), "w", encoding="utf-8") as f:
        f.write("\n".join(header) + "\n\n" + arch_text + "\n")
    print("saved", os.path.join(out, "model_architecture.txt"))

    cats = list(summary)
    vals = np.array([summary[c] for c in cats], float)
    fig, ax = plt.subplots(figsize=(9, 0.5 * len(cats) + 1.8))
    ypos = np.arange(len(cats))[::-1]
    ax.barh(ypos, vals / 1e6, color="#4c72b0")
    for y, v in zip(ypos, vals):
        ax.text(v / 1e6, y, f"  {v / 1e6:.1f}M ({100 * v / base_total:.1f}%)", va="center", fontsize=9)
    ax.set_yticks(ypos)
    ax.set_yticklabels(cats)
    ax.set_xlim(0, vals.max() / 1e6 * 1.3)
    ax.set_xlabel("parameters (millions)")
    ax.set_title(f"Frozen base-model parameters by component ({base_total / 1e9:.3f}B total)")
    savefig(fig, out, "param_breakdown.png")

    by_mod = [sum(p for _, m, p in lora_items if m == mod) for mod in MODULES]
    fig, (a1, a2) = plt.subplots(1, 2, figsize=(12, 4.2), gridspec_kw={"width_ratios": [3, 2]})
    a1.bar(MODULES, np.array(by_mod) / 1e6, color=["#dd8452"] * 4 + ["#55a868"] * 3)
    for i, v in enumerate(by_mod):
        a1.text(i, v / 1e6, f"{v / 1e6:.2f}M", ha="center", va="bottom", fontsize=8)
    a1.set_ylabel("LoRA parameters (millions)")
    a1.set_title(f"Trainable LoRA parameters per module type (r={rank}, all {len(lora_items) // len(MODULES)} layers)")
    a1.tick_params(axis="x", rotation=30)
    a2.bar(["base (frozen)", "LoRA (trained)"], [base_total / 1e6, lora_total / 1e6], color=["#8c8c8c", "#dd8452"])
    a2.set_yscale("log")
    a2.set_ylabel("parameters (millions, log scale)")
    a2.set_title(f"LoRA trains {100 * lora_total / base_total:.2f}% of the model")
    for i, v in enumerate([base_total, lora_total]):
        a2.text(i, v / 1e6, f"{v / 1e6:,.1f}M", ha="center", va="bottom", fontsize=9)
    savefig(fig, out, "lora_params.png")

    draw_architecture(cfg, rank, lora_total, base_total, model_name, out)


def cmd_arch(args):
    import torch
    from transformers import AutoConfig, AutoModelForCausalLM

    name = args.model or os.environ.get("BASE_MODEL", "meta-llama/Llama-3.2-1B")
    hf_cfg = AutoConfig.from_pretrained(name)
    with torch.device("meta"):  # builds the structure only: no weights are downloaded or allocated
        model = AutoModelForCausalLM.from_config(hf_cfg)
    base_items = [(n, p.numel()) for n, p in model.named_parameters()]
    lora_items = []
    for n, m in model.named_modules():
        short = n.split(".")[-1]
        if isinstance(m, torch.nn.Linear) and short in MODULES:
            layer = re.search(r"layers\.(\d+)\.", n)
            if layer:  # LoRA adds A (r x in) and B (out x r)
                lora_items.append((int(layer.group(1)), short, args.rank * (m.in_features + m.out_features)))
    cfg = dict(layers=hf_cfg.num_hidden_layers, hidden=hf_cfg.hidden_size, inter=hf_cfg.intermediate_size,
               heads=hf_cfg.num_attention_heads,
               kv_heads=getattr(hf_cfg, "num_key_value_heads", hf_cfg.num_attention_heads),
               vocab=hf_cfg.vocab_size, tied=getattr(hf_cfg, "tie_word_embeddings", False))
    build_arch(base_items, lora_items, cfg, name, args.rank, str(model), args.out)


