def build_html(states, query_langs, title, nli):
    css = ("body{font-family:'Noto Sans','Noto Sans Devanagari','Noto Sans Kannada',sans-serif;margin:24px}"
           "table{border-collapse:collapse;margin:12px 0 28px;width:100%}"
           "th,td{border:1px solid #ccc;padding:6px 8px;vertical-align:top;font-size:14px}"
           "th{background:#f0f0f0}.known{background:#fde2e2}.forgot{background:#dff3e0}")
    parts = [f"<html><head><meta charset='utf-8'><title>{html.escape(title)}</title><style>{css}</style></head><body>",
             f"<h1>{html.escape(title)}</h1>"]
    if nli:
        parts.append("<p><span class='known'>red = answer still conveys the fact (NLI)</span> &nbsp; "
                     "<span class='forgot'>green = fact no longer conveyed</span></p>")
    names = list(states)
    for q in query_langs:
        parts.append(f"<h2>Questions asked in: {html.escape(q)}</h2><table><tr><th>#</th><th>Question</th>"
                     f"<th>Reference answer</th>" + "".join(f"<th>{html.escape(n)}</th>" for n in names) + "</tr>")
        base_rows = states[names[0]][q]
        for i, r in enumerate(base_rows):
            cells = ""
            for n in names:
                e = states[n][q][i]
                cls = "" if e["known"] is None else (" class='known'" if e["known"] else " class='forgot'")
                cells += f"<td{cls}>{html.escape(e['output'])}</td>"
            parts.append(f"<tr><td>{i + 1}</td><td>{html.escape(r['question'])}</td>"
                         f"<td>{html.escape(r['reference'])}</td>{cells}</tr>")
        parts.append("</table>")
    parts.append("</body></html>")
    return "\n".join(parts)


def cmd_outputs(args):
    from peft import PeftModel

    from src.common.model_utils import generate_answers, load_injected, load_qa, load_tokenizer

    tok = load_tokenizer()
    scorer = None
    if args.nli:
        from src.eval.nli_score import NLIScorer
        scorer = NLIScorer()
    model = load_injected(args.injected)

    def run(m):
        res = {}
        for q in args.query_langs:
            recs = load_qa(q, "forget", limit=args.n)
            preds = generate_answers(m, tok, [r["question"] for r in recs])
            flags = scorer.score(preds, [r["answer"] for r in recs])[1] if scorer else [None] * len(preds)
            res[q] = [{"question": r["question"], "reference": r["answer"], "output": p, "known": fl}
                      for r, p, fl in zip(recs, preds, flags)]
        return res

    states = OrderedDict([("baseline (before unlearning)", run(model))])
    for ul in args.unlearn_langs:
        pm = PeftModel.from_pretrained(model, f"checkpoints/{args.method}_{ul}")
        states[f"{args.method.upper()} unlearned in {ul}"] = run(pm)
        model = pm.unload()  # strip the adapter, keep the injected base for the next one

    os.makedirs(args.out, exist_ok=True)
    with open(os.path.join(args.out, "model_outputs.json"), "w", encoding="utf-8") as f:
        json.dump(states, f, ensure_ascii=False, indent=2)
    with open(os.path.join(args.out, "model_outputs.html"), "w", encoding="utf-8") as f:
        f.write(build_html(states, args.query_langs, "Model outputs before and after unlearning", scorer is not None))
    print("saved", os.path.join(args.out, "model_outputs.json"), "and model_outputs.html")


