MODULES = ["q_proj", "k_proj", "v_proj", "o_proj", "gate_proj", "up_proj", "down_proj"]
ATTN = MODULES[:4]
MODULE_COLORS = ["#4c72b0", "#6a8fcf", "#8fb0e3", "#b5cdf0", "#dd8452", "#e8a97c", "#f2cfb3"]
CATEGORY_ORDER = ["token embeddings", "attention.q_proj", "attention.k_proj", "attention.v_proj",
                  "attention.o_proj", "mlp.gate_proj", "mlp.up_proj", "mlp.down_proj",
                  "layer norms", "lm_head", "other"]
LORA_RE = re.compile(r"layers\.(\d+)\..*?(" + "|".join(MODULES) + r")\.lora_([AB])")


# ------------------------------------------------------------------ small helpers
def savefig(fig, out, name):
    os.makedirs(out, exist_ok=True)
    path = os.path.join(out, name)
    fig.savefig(path, dpi=160, bbox_inches="tight")
    plt.close(fig)
    print("saved", path)


def write_csv(out, name, header, rows):
    os.makedirs(out, exist_ok=True)
    path = os.path.join(out, name)
    with open(path, "w", encoding="utf-8", newline="") as f:
        w = csv.writer(f)
        w.writerow(header)
        w.writerows(rows)
    print("saved", path)


def write_index(out):
    """results/figures/README.md embedding every PNG, so GitHub shows them on the folder page."""
    files = sorted(os.listdir(out))
    lines = ["# Model visualisations and results", "",
             "Generated by `python -m src.eval.visualize`. Re-run it to refresh.", ""]
    for f in files:
        if f.endswith(".png"):
            lines += [f"## {f[:-4].replace('_', ' ')}", f"![{f}]({f})", ""]
    others = [f for f in files if not f.endswith(".png") and f != "README.md"]
    if others:
        lines += ["## Other files", ""] + [f"- [{f}]({f})" for f in others]
    with open(os.path.join(out, "README.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print("saved", os.path.join(out, "README.md"))


# ------------------------------------------------------------------ RESULTS (no model needed)
def draw_heatmap(ax, data, rows, cols, title, cmap):
    ax.imshow(np.ma.masked_invalid(data), vmin=0, vmax=1, cmap=cmap, aspect="auto")
    ax.set_xticks(range(len(cols)))
    ax.set_xticklabels(cols)
    ax.set_yticks(range(len(rows)))
    ax.set_yticklabels(rows)
    ax.set_xlabel("language queried")
    ax.set_ylabel("unlearned in")
    for i in range(len(rows)):
        for j in range(len(cols)):
            v = data[i, j]
            if not np.isnan(v):
                ax.text(j, i, f"{v:.2f}", ha="center", va="center", fontsize=11,
                        color="white" if (v < 0.15 or v > 0.85) else "black")
    ax.set_title(title, fontsize=10)


def matrix_data(rows, cols, split):
    data = np.full((len(rows), len(cols)), np.nan)
    for i, cells in enumerate(rows.values()):
        for j, q in enumerate(cols):
            if q in cells:
                data[i, j] = cells[q][split]["rate"]
    return data


def plot_results(matrix_path, out):
    if not os.path.exists(matrix_path):
        print(f"[results] {matrix_path} not found - run src.eval.transfer_matrix first")
        return
    with open(matrix_path, encoding="utf-8") as f:
        res = json.load(f)
    baseline = res.get("baseline", {}).get("none")
    for method, by_lang in res.items():
        if method == "baseline":
            continue
        rows = OrderedDict()
        if baseline:
            rows["baseline (no unlearning)"] = baseline
        for ul, cells in by_lang.items():
            rows[f"{method.upper()} / {ul}"] = cells
        cols = sorted({q for cells in rows.values() for q in cells}, key=lambda q: (q != "english", q))
        fig, axes = plt.subplots(1, 2, figsize=(5 + 2.2 * len(cols) * 2, 1.6 + 0.8 * len(rows)))
        draw_heatmap(axes[0], matrix_data(rows, cols, "forget"), list(rows), cols,
                     "FORGET set: fraction still answered\n(red = fact still known = leaked)", "RdYlGn_r")
        draw_heatmap(axes[1], matrix_data(rows, cols, "retain"), list(rows), cols,
                     "RETAIN set: fraction still answered\n(green = knowledge preserved)", "RdYlGn")
        axes[1].set_yticklabels([])  # same rows as the left panel
        axes[1].set_ylabel("")
        fig.suptitle(f"Cross-lingual unlearning transfer ({method.upper()})", fontsize=12, y=1.12)
        fig.tight_layout()
        savefig(fig, out, f"leak_matrix_{method}.png")

        for ul, cells in by_lang.items():
            qs = [q for q in cols if q in cells]
            series = [("baseline forget", baseline, "forget", "#c44e52", 0.55),
                      (f"after {method.upper()} forget", cells, "forget", "#c44e52", 1.0),
                      ("baseline retain", baseline, "retain", "#55a868", 0.55),
                      (f"after {method.upper()} retain", cells, "retain", "#55a868", 1.0)]
            fig, ax = plt.subplots(figsize=(1.8 + 2.2 * len(qs), 4.2))
            width = 0.2
            for k, (label, src, split, color, alpha) in enumerate(series):
                vals = [src[q][split]["rate"] if (src and q in src) else np.nan for q in qs]
                ax.bar(np.arange(len(qs)) + (k - 1.5) * width, vals, width, label=label,
                       color=color, alpha=alpha, edgecolor="black", linewidth=0.5)
            ax.set_xticks(range(len(qs)))
            ax.set_xticklabels(qs)
            ax.set_ylim(0, 1.05)
            ax.set_ylabel("fraction answered (NLI entailment)")
            ax.set_xlabel("language queried")
            n = cells[qs[0]]["forget"].get("n", "?") if qs else "?"
            ax.set_title(f"Unlearned in {ul} with {method.upper()} (n={n} questions per cell)")
            ax.legend(fontsize=8, ncol=2, loc="upper center", bbox_to_anchor=(0.5, -0.18))
            savefig(fig, out, f"summary_{method}_{ul}.png")


def plot_logs(out):
    inj = "results/logs/injection_loss.json"
    if os.path.exists(inj):
        with open(inj, encoding="utf-8") as f:
            hist = json.load(f)["history"]
        fig, ax = plt.subplots(figsize=(6, 3.8))
        ax.plot([h["epoch"] for h in hist], [h["mean_loss"] for h in hist], marker="o", color="#4c72b0")
        ax.set_xlabel("epoch")
        ax.set_ylabel("mean training loss (answer tokens)")
        ax.set_title("Knowledge injection (LoRA)")
        ax.grid(alpha=0.3)
        savefig(fig, out, "injection_loss.png")
    else:
        print(f"[results] {inj} not found (re-run inject_knowledge with the updated script)")

    ga_logs = sorted(glob.glob("results/logs/ga_*_loss.json"))
    if ga_logs:
        fig, ax = plt.subplots(figsize=(6.5, 3.8))
        cap = None
        for p in ga_logs:
            with open(p, encoding="utf-8") as f:
                d = json.load(f)
            ax.plot([h["step"] for h in d["history"]], [h["loss"] for h in d["history"]],
                    marker=".", label=d["lang"])
            cap = d.get("cap", cap)
        if cap is not None:
            ax.axhline(cap, color="gray", linestyle="--", label=f"loss cap {cap}")
        ax.set_xlabel("gradient-ascent step")
        ax.set_ylabel("forget-set loss (rises = forgetting)")
        ax.set_title("Gradient-ascent unlearning (LoRA)")
        ax.legend()
        ax.grid(alpha=0.3)
        savefig(fig, out, "ga_forget_loss.png")
    else:
        print("[results] no results/logs/ga_*_loss.json found")


