def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("cmd", choices=["results", "adapters", "arch", "outputs", "all"])
    ap.add_argument("--method", default="ga")
    ap.add_argument("--unlearn_langs", nargs="+", default=["hindi"])
    ap.add_argument("--query_langs", nargs="+", default=["english", "hindi"])
    ap.add_argument("--n", type=int, default=5, help="questions per language in the outputs report")
    ap.add_argument("--nli", action="store_true", help="colour outputs by NLI verdict (loads the NLI model)")
    ap.add_argument("--injected", default="checkpoints/injected")
    ap.add_argument("--adapters", nargs="*", default=None, help="adapter folders (default: all in checkpoints/)")
    ap.add_argument("--matrix", default="results/transfer_matrix.json")
    ap.add_argument("--model", default=None, help="HF model id for 'arch' (default: $BASE_MODEL or Llama-3.2-1B)")
    ap.add_argument("--rank", type=int, default=16, help="LoRA rank used for the parameter counts")
    ap.add_argument("--out", default="results/figures")
    args = ap.parse_args()

    steps = {"results": cmd_results, "adapters": cmd_adapters, "arch": cmd_arch, "outputs": cmd_outputs}
    if args.cmd == "all":
        for name, fn in steps.items():
            try:
                print(f"\n=== {name} ===")
                fn(args)
            except Exception as e:  # keep going so one missing input does not block the rest
                print(f"[{name}] skipped: {type(e).__name__}: {e}")
    else:
        steps[args.cmd](args)
    os.makedirs(args.out, exist_ok=True)
    write_index(args.out)


if __name__ == "__main__":
    main()
